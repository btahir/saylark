import AppKit
import SaylarkCore

/// Everything that was on a pasteboard: every item, every type, as raw bytes, in order.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Entry: Sendable, Equatable {
        public var type: String
        public var data: Data
        public init(type: String, data: Data) {
            self.type = type
            self.data = data
        }
    }

    public struct Item: Sendable, Equatable {
        public var entries: [Entry]
        public init(_ entries: [Entry]) { self.entries = entries }
        public var types: [String] { entries.map(\.type) }

        /// The pasteboard server derives `public.utf16-external-plain-text` from UTF-8 text on
        /// its own, and where it puts it in the type list depends on how the item was written
        /// (seen on macOS 27.2: `declareTypes` puts it last, `NSPasteboardItem` puts it after the
        /// first type). Same bytes for every type, same order apart from that derived type.
        public func sameContent(as other: Item) -> Bool {
            let derived = "public.utf16-external-plain-text"
            guard Set(types) == Set(other.types), types.filter({ $0 != derived }) == other.types.filter({ $0 != derived }) else { return false }
            return entries.allSatisfy { other.data($0.type) == $0.data }
        }
        public func data(_ type: String) -> Data? { entries.first { $0.type == type }?.data }
    }

    public var items: [Item]
    /// The pasteboard's change count when the snapshot was taken.
    public var changeCount: Int
    /// Types that were listed but gave no data (a lazy provider that has quit, a file promise).
    /// They cannot be restored.
    public var droppedTypes: [String]

    public init(items: [Item], changeCount: Int, droppedTypes: [String] = []) {
        self.items = items
        self.changeCount = changeCount
        self.droppedTypes = droppedTypes
    }

    /// Same items, same content (see `Item.sameContent`).
    public func sameContent(as other: PasteboardSnapshot) -> Bool {
        items.count == other.items.count && zip(items, other.items).allSatisfy { $0.sameContent(as: $1) }
    }

    public var byteCount: Int { items.reduce(0) { $0 + $1.entries.reduce(0) { $0 + $1.data.count } } }
    public var isEmpty: Bool { items.isEmpty }
}

/// The nspasteboard.org markers that tell clipboard managers (Maccy, Raycast, Paste, Alfred…)
/// to skip an entry, so our transient text never lands in the user's clipboard history.
public enum PasteboardMarker {
    /// "This will be gone in a moment; don't record it."
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// "Don't show or store the contents."
    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// "Not copied by the user."
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// The bundle ID of the app that wrote the entry.
    public static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    /// Saylark's own marker, so a later write can tell the clipboard still holds our text.
    public static let saylark = NSPasteboard.PasteboardType("app.saylark.transient")

    public static let all: [NSPasteboard.PasteboardType] = [transient, concealed, autoGenerated, source, saylark]
}

public enum PasteboardError: Error, Equatable, CustomStringConvertible {
    case tooLarge(bytes: Int)
    /// Reading would show the macOS privacy prompt, or is denied.
    case notReadable

    public var description: String {
        switch self {
        case .tooLarge(let b): "clipboard snapshot is too large to keep (\(b) bytes)"
        case .notReadable: "the clipboard can't be read without a prompt"
        }
    }
}

/// The clipboard, as the insertion path needs it. All calls on the main actor (AppKit's
/// pasteboard and its data-provider callbacks live there).
@MainActor
public protocol Pasteboard: AnyObject {
    var changeCount: Int { get }
    /// Whether `snapshot()` can read the contents without the macOS privacy prompt. Checking this
    /// never reads the contents.
    var access: InsertionMachine.ClipboardAccess { get }
    /// Reads every item and type. Lazily provided types are resolved now.
    func snapshot() throws -> PasteboardSnapshot
    /// Replaces the contents with `text` as a promise, marked transient for clipboard managers and
    /// kept off other devices. `onRead` runs on the main actor when a reader asks for the text.
    /// Returns the change count of this write.
    func writeTransient(_ text: String, onRead: @escaping @MainActor () -> Void) -> Int
    /// Puts `snapshot` back, but only if the change count is still `expected` (nobody else wrote
    /// meanwhile). Returns false and changes nothing otherwise.
    func restore(_ snapshot: PasteboardSnapshot, ifChangeCount expected: Int) -> Bool
    /// A plain, permanent copy (the card's Copy button).
    func writePlain(_ text: String)
    /// Reads the clipboard once on purpose, so macOS shows its "paste from other apps" prompt now
    /// (from a user's click in onboarding or settings), then reports the access that results.
    func requestAccess() -> InsertionMachine.ClipboardAccess
}

/// A real `NSPasteboard`. Production uses `.general`; tests and the harness use a named one.
@MainActor
public final class SystemPasteboard: Pasteboard {
    public let pasteboard: NSPasteboard
    /// Snapshots above this many bytes are refused (the paste falls back to accessibility or the
    /// card instead of risking an unrestorable clipboard).
    public var maxSnapshotBytes = 256 * 1024 * 1024
    /// Bundle ID written as `org.nspasteboard.source`.
    public var sourceID: String
    /// Which markers go on transient writes.
    public var markers: [NSPasteboard.PasteboardType] = PasteboardMarker.all
    private var provider: TransientProvider?

    public init(_ pasteboard: NSPasteboard, sourceID: String = Bundle.main.bundleIdentifier ?? "app.saylark") {
        self.pasteboard = pasteboard
        self.sourceID = sourceID
    }

    /// The system clipboard. Production only: never in tests or verification runs.
    public static func general() -> SystemPasteboard { SystemPasteboard(.general) }

    /// A private pasteboard that no other app reads. Call `release()` when done.
    public static func named(_ name: String = "app.saylark.test.\(UUID().uuidString)") -> SystemPasteboard {
        SystemPasteboard(NSPasteboard(name: NSPasteboard.Name(name)))
    }

    public func release() { pasteboard.releaseGlobally() }

    public var changeCount: Int { pasteboard.changeCount }

    public var access: InsertionMachine.ClipboardAccess {
        // `.default` on the general pasteboard means "ask on programmatic access" (AppKit header,
        // macOS 15.4+): the first read shows the alert. Named pasteboards report `.default` too
        // but always allow, per the same header.
        switch pasteboard.accessBehavior {
        case .alwaysAllow: return .allowed
        case .alwaysDeny: return .denied
        case .ask: return .wouldPrompt
        case .default: return pasteboard.name == .general ? .wouldPrompt : .allowed
        @unknown default: return .wouldPrompt
        }
    }

    public func snapshot() throws -> PasteboardSnapshot {
        guard access == .allowed else { throw PasteboardError.notReadable }
        let count = pasteboard.changeCount
        var items: [PasteboardSnapshot.Item] = []
        var dropped: [String] = []
        var bytes = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [PasteboardSnapshot.Entry] = []
            for type in item.types {
                if let data = item.data(forType: type) {
                    bytes += data.count
                    if bytes > maxSnapshotBytes { throw PasteboardError.tooLarge(bytes: bytes) }
                    entries.append(.init(type: type.rawValue, data: data))
                } else {
                    dropped.append(type.rawValue)
                }
            }
            items.append(.init(entries))
        }
        return PasteboardSnapshot(items: items, changeCount: count, droppedTypes: dropped)
    }

    public func writeTransient(_ text: String, onRead: @escaping @MainActor () -> Void) -> Int {
        // Clears the contents and keeps the new entry off Universal Clipboard.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let provider = TransientProvider(text: text, onRead: onRead)
        self.provider = provider
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        for marker in markers {
            item.setData(marker == PasteboardMarker.source ? Data(sourceID.utf8) : Data(), forType: marker)
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    public func restore(_ snapshot: PasteboardSnapshot, ifChangeCount expected: Int) -> Bool {
        // The window between this check and clearContents is a few microseconds; a copy landing
        // exactly inside it would be overwritten. Nothing in AppKit closes it.
        guard pasteboard.changeCount == expected else { return false }
        pasteboard.clearContents()
        provider = nil
        guard !snapshot.items.isEmpty else { return true }
        let items = snapshot.items.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for e in saved.entries { item.setData(e.data, forType: NSPasteboard.PasteboardType(e.type)) }
            return item
        }
        pasteboard.writeObjects(items)
        return true
    }

    public func writePlain(_ text: String) {
        pasteboard.clearContents()
        provider = nil
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString(sourceID, forType: PasteboardMarker.source)
        pasteboard.writeObjects([item])
    }

    public func requestAccess() -> InsertionMachine.ClipboardAccess {
        // One read of the contents is what makes macOS ask. The value is dropped at once.
        if access == .wouldPrompt { _ = pasteboard.string(forType: .string) }
        return access
    }
}

/// Serves the promised text and reports each request: the read receipt.
final class TransientProvider: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    let text: String
    let onRead: @MainActor () -> Void

    init(text: String, onRead: @escaping @MainActor () -> Void) {
        self.text = text
        self.onRead = onRead
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        let onRead = self.onRead
        if Thread.isMainThread {
            MainActor.assumeIsolated { onRead() }
        } else {
            DispatchQueue.main.async { MainActor.assumeIsolated { onRead() } }
        }
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}
}

/// An in-memory pasteboard for tests. Simulates a target reading the promise (`readString`),
/// another app writing meanwhile (`externalWrite`), and the privacy setting (`access`).
@MainActor
public final class MemoryPasteboard: Pasteboard {
    public private(set) var changeCount = 0
    public var access: InsertionMachine.ClipboardAccess = .allowed
    /// What the simulated prompt answers when `requestAccess()` is called while it would prompt.
    public var promptAnswer: InsertionMachine.ClipboardAccess = .allowed
    public private(set) var accessRequests = 0
    public private(set) var items: [PasteboardSnapshot.Item] = []
    /// How many times the contents were read for a snapshot.
    public private(set) var snapshotReads = 0
    public private(set) var restores = 0
    private var promise: (text: String, onRead: @MainActor () -> Void)?

    public init(items: [PasteboardSnapshot.Item] = []) {
        self.items = items
    }

    public func snapshot() throws -> PasteboardSnapshot {
        guard access == .allowed else { throw PasteboardError.notReadable }
        snapshotReads += 1
        return PasteboardSnapshot(items: items, changeCount: changeCount)
    }

    public func writeTransient(_ text: String, onRead: @escaping @MainActor () -> Void) -> Int {
        changeCount += 1
        items = [.init([.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data(text.utf8)),
                        .init(type: PasteboardMarker.transient.rawValue, data: Data())])]
        promise = (text, onRead)
        return changeCount
    }

    public func restore(_ snapshot: PasteboardSnapshot, ifChangeCount expected: Int) -> Bool {
        guard changeCount == expected else { return false }
        changeCount += 1
        items = snapshot.items
        promise = nil
        restores += 1
        return true
    }

    public func writePlain(_ text: String) {
        changeCount += 1
        promise = nil
        items = [.init([.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data(text.utf8))])]
    }

    public func requestAccess() -> InsertionMachine.ClipboardAccess {
        accessRequests += 1
        if access == .wouldPrompt { access = promptAnswer }
        return access
    }

    /// What a target's ⌘V would get. Fires the read receipt if our promise is up.
    @discardableResult
    public func readString() -> String? {
        if let promise { promise.onRead() }
        return items.first?.data(NSPasteboard.PasteboardType.string.rawValue).flatMap { String(data: $0, encoding: .utf8) }
    }

    /// Another app copies something.
    public func externalWrite(_ text: String) {
        changeCount += 1
        promise = nil
        items = [.init([.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data(text.utf8))])]
    }
}
